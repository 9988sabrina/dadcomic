const listeners = new Set();

export function getLang() {
  const ui = document.documentElement.dataset.ui;
  if (ui === "zh" || ui === "en") return ui;
  return "en";
}

export function t(key) {
  const lang = getLang();
  const table = STR[lang] || STR.en;
  if (table[key] != null) return table[key];
  if (STR.en[key] != null) return STR.en[key];
  return key;
}

export function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = t(node.getAttribute("data-i18n"));
    const attr = node.getAttribute("data-i18n-attr");
    if (attr) node.setAttribute(attr, value);
    else node.textContent = value;
  });
}

export function onLang(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function setLang(lang) {
  const next = lang === "zh" ? "zh" : "en";
  try {
    localStorage.setItem(KEY, next);
  } catch (err) {
    /* private mode */
  }
  document.documentElement.lang = next === "zh" ? "zh-Hans" : "en";
  document.documentElement.dataset.ui = next;
  applyI18n();
  listeners.forEach((fn) => fn(next));
}
